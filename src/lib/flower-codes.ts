/** A random name that isn't in `taken`, or undefined once every name is used. */
export function randomFlowerCode(taken: string[]) {
	const used = new Set(taken.map(flowerCodeKey));
	const free = GIRL_NAMES.filter((name) => !used.has(flowerCodeKey(name)));
	return free[Math.floor(Math.random() * free.length)];
}
